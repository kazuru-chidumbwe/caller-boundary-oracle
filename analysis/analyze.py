#!/usr/bin/env python3
"""Summarise verified run artifacts into the tables reported for RQ2 and RQ3.

Input: suite log directories (each verified by classifier/verify_manifest.py) and, optionally,
the iOS run directory. Output, under --out:

  behaviour.csv      outcome counts per arm x mechanism x fault point (behaviour classes)
  sw-dependence.csv  cells where an arm's outcome depends on the status word
  agreement.csv      pairwise agreement and Cohen's kappa between arms over shared cells
  crosscheck.csv     harness chip vs independent chip, same arm and same fault
  repeat.csv         PACE positive-control success rate per library, Wilson 95% interval
  RESULTS.md         the same tables in Markdown

Standard library only.
"""

from __future__ import annotations

import argparse
import csv
import itertools
import json
import math
import re
from collections import Counter, defaultdict
from pathlib import Path

SCORED = ("silent", "status_only", "surfaced")
SKIP = {"artifact-manifest.json", "environment.json"}
# Arms in reporting order: (library, variant) -> label
ARM_ORDER = [
    ("gmrtd", "8fea245-default", "gmrtd 0.45.0 default"),
    ("gmrtd", "8fea245-guard", "gmrtd 0.45.0 + guard"),
    ("gmrtd", "64bd6ab-default", "gmrtd 1.1.3 default"),
    ("gmrtd", "64bd6ab-allow-fallback", "gmrtd 1.1.3 opt-in fallback"),
    ("gmrtd", "64bd6ab-guard", "gmrtd 1.1.3 + guard"),
    ("gmrtd", "b861835-default", "gmrtd 1.3.2 default"),
    ("gmrtd", "b861835-allow-fallback", "gmrtd 1.3.2 opt-in fallback"),
    ("gmrtd", "b861835-guard", "gmrtd 1.3.2 + guard"),
    ("jmrtd", "propagate", "JMRTD 0.8.9 propagate"),
    ("jmrtd", "catch-continue", "JMRTD 0.8.9 catch-and-continue"),
    ("emrtd-dotnet", "default", "emrtd-dotnet"),
    ("dmrtd", "default", "dmrtd"),
    ("nfcpassportreader", "default", "NFCPassportReader"),
]
LABEL = {(lib, var): label for lib, var, label in ARM_ORDER}
ORDER = {(lib, var): i for i, (lib, var, _) in enumerate(ARM_ORDER)}


def load_runs(dirs: list[Path]) -> list[dict]:
    runs = []
    for d in dirs:
        for f in sorted(d.rglob("*.json")):
            if f.name in SKIP or f.name.startswith("summary") or f.name == "plan.json":
                continue
            r = json.loads(f.read_text(encoding="utf-8"))
            if "outcome" not in r or "library" not in r:
                continue
            r["_suite"] = d.name.split("-2026")[0].replace("suite-", "")
            runs.append(r)
    return runs


def arm(r: dict) -> tuple[str, str]:
    return r["library"], r.get("variant", "default")


def chip(r: dict) -> str:
    return "independent" if r["test_case"].startswith("VSC-") else "harness"


def fault_kind(test_case: str) -> str:
    m = re.search(r"-(6[0-9a-f]{3}|no-response|timeout|transport-abort)$", test_case)
    return m.group(1).upper() if m and m.group(1)[0] == "6" else (m.group(1) if m else "none")


def point(r: dict) -> str:
    fp = r.get("fault_point") or ""
    if fp:
        return fp
    return "control" if r["test_case"].startswith(("CTRL-", "VSC-pace-success")) else "unknown"


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (math.nan, math.nan)
    p = k / n
    den = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return max(0.0, centre - half), min(1.0, centre + half)


def cohen_kappa(a: list[str], b: list[str]) -> float:
    n = len(a)
    if n == 0:
        return math.nan
    po = sum(x == y for x, y in zip(a, b)) / n
    ca, cb = Counter(a), Counter(b)
    pe = sum(ca[c] * cb[c] for c in set(a) | set(b)) / (n * n)
    return math.nan if pe == 1 else (po - pe) / (1 - pe)


def fmt(x: float) -> str:
    return "n/a" if x != x else f"{x:.2f}"


def write_csv(path: Path, header: list[str], rows: list[list]) -> None:
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def md_table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("dirs", nargs="+", type=Path, help="verified suite log directories (and the iOS run directory)")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent / "out")
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    runs = load_runs(args.dirs)
    single = [r for r in runs if r["_suite"] != "independent-repeat"]
    repeat = [r for r in runs if r["_suite"] == "independent-repeat"]
    md = ["# Results (generated by analysis/analyze.py)", "",
          f"Runs read: {len(runs)} ({len(single)} single-run entries, {len(repeat)} repeat runs).", ""]

    # 1. Behaviour classes: arm x mechanism x chip x point -> outcome counts over failure kinds.
    groups: dict[tuple, Counter] = defaultdict(Counter)
    for r in single:
        groups[(arm(r), r["mechanism"], chip(r), point(r))][r["outcome"]] += 1
    rows = []
    for (a, mech, ch, pt), c in sorted(groups.items(), key=lambda kv: (ORDER.get(kv[0][0], 99), kv[0][1:])):
        cls = ", ".join(f"{o} {n}" for o, n in sorted(c.items(), key=lambda kv: -kv[1]))
        rows.append([LABEL.get(a, "/".join(a)), mech, ch, pt, sum(c.values()), cls])
    hdr = ["arm", "mechanism", "chip", "fault point", "runs", "outcomes"]
    write_csv(args.out / "behaviour.csv", hdr, rows)
    md += ["## Behaviour classes per arm, mechanism and fault point", "", md_table(hdr, rows), ""]

    # 2. Status-word dependence: cells where one arm's outcome varies across failure kinds.
    dep = []
    for (a, mech, ch, pt), c in groups.items():
        if len([o for o in c if o in SCORED]) > 1:
            kinds = defaultdict(list)
            for r in single:
                if (arm(r), r["mechanism"], chip(r), point(r)) == (a, mech, ch, pt):
                    kinds[r["outcome"]].append(fault_kind(r["test_case"]))
            dep.append([LABEL.get(a, "/".join(a)), mech, ch, pt,
                        "; ".join(f"{o}: {' '.join(sorted(set(k)))}" for o, k in sorted(kinds.items()))])
    dep.sort(key=lambda row: row[:4])
    hdr = ["arm", "mechanism", "chip", "fault point", "outcome by failure kind"]
    write_csv(args.out / "sw-dependence.csv", hdr, dep)
    md += ["## Outcomes that depend on the failure kind", "", md_table(hdr, dep) if dep else "None.", ""]

    # 3. Pairwise agreement and Cohen's kappa over cells both arms scored.
    by_cell: dict[str, dict] = defaultdict(dict)
    for r in single:
        if r["outcome"] in SCORED:
            by_cell[r["test_case"]][arm(r)] = r["outcome"]
    arms = sorted({a for cell in by_cell.values() for a in cell}, key=lambda a: ORDER.get(a, 99))
    rows = []
    for a, b in itertools.combinations(arms, 2):
        shared = [c for c in by_cell.values() if a in c and b in c]
        if not shared:
            continue
        xa, xb = [c[a] for c in shared], [c[b] for c in shared]
        agree = sum(x == y for x, y in zip(xa, xb))
        rows.append([LABEL.get(a, a), LABEL.get(b, b), len(shared), agree, f"{agree / len(shared):.2f}", fmt(cohen_kappa(xa, xb))])
    hdr = ["arm A", "arm B", "shared cells", "same outcome", "agreement", "Cohen's kappa"]
    write_csv(args.out / "agreement.csv", hdr, rows)
    md += ["## Pairwise agreement between arms (cells both arms scored)", "",
           "Kappa is n/a when both arms give one outcome throughout (no variation to correct for chance).", "",
           md_table(hdr, rows), ""]

    # 4. Cross-check: same arm, same mechanism, point and failure kind on both chips.
    pts = defaultdict(dict)
    for r in single:
        key = (arm(r), r["mechanism"], re.sub(r"_step1$", "", point(r).replace("general_authenticate_step1", "general_authenticate")),
               fault_kind(r["test_case"]))
        pts[key][chip(r)] = r["outcome"]
    rows = []
    for (a, mech, pt, kind), v in sorted(pts.items(), key=lambda kv: (ORDER.get(kv[0][0], 99), kv[0][1:])):
        if "harness" in v and "independent" in v:
            rows.append([LABEL.get(a, "/".join(a)), mech, pt, kind, v["harness"], v["independent"],
                         "yes" if v["harness"] == v["independent"] else "NO"])
    same = sum(1 for r in rows if r[-1] == "yes")
    applicable = sum(1 for r in rows if "not_applicable" not in (r[4], r[5]))
    same_applicable = sum(1 for r in rows if r[-1] == "yes" and "not_applicable" not in (r[4], r[5]))
    hdr = ["arm", "mechanism", "fault point", "failure", "harness chip", "independent chip", "same"]
    write_csv(args.out / "crosscheck.csv", hdr, rows)
    md += ["## Cross-check: harness chip vs independent chip", "",
           f"{same} of {len(rows)} paired cells give the same outcome on both chips "
           f"({same_applicable} of {applicable} where both runs were applicable).", "", md_table(hdr, rows), ""]

    # 5. Repeat suite: PACE positive control success per library, Wilson 95% interval.
    rep: dict[tuple, list] = defaultdict(list)
    for r in repeat:
        rep[arm(r)].append(bool(r["observation"]["succeeded"]))
    rows = []
    for a in sorted(rep, key=lambda a: ORDER.get(a, 99)):
        k, n = sum(rep[a]), len(rep[a])
        lo, hi = wilson(n - k, n)
        rows.append([LABEL.get(a, a), n, k, n - k, f"{(n - k) / n:.3f}", f"[{lo:.3f}, {hi:.3f}]"])
    hdr = ["arm", "runs", "PACE succeeded", "PACE failed", "failure rate", "Wilson 95% CI"]
    write_csv(args.out / "repeat.csv", hdr, rows)
    md += ["## PACE positive control on the independent chip (repeat suite)", "", md_table(hdr, rows), ""]

    (args.out / "RESULTS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(runs)} runs -> {args.out}")


if __name__ == "__main__":
    main()
