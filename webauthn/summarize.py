#!/usr/bin/env python3
"""Summarise a WebAuthn run directory (results.jsonl, RUN.json, VERIFY.txt) into RESULTS.md in that directory.

Usage: python3 webauthn/summarize.py <run-dir>
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main() -> None:
    OUT = Path(sys.argv[1])
    rows = [json.loads(l) for l in (OUT / "results.jsonl").open(encoding="utf-8")]
    run = json.loads((OUT / "RUN.json").read_text(encoding="utf-8"))
    libs = list(dict.fromkeys(r["library"] for r in rows))
    lines = ["# WebAuthn arm: results (generated by webauthn/summarize.py)", "",
             f"Harness `{run['harness_commit'][:7]}` (dirty: {run['harness_dirty']}), oracle `classifier/observability.py` "
             f"SHA-256 `{run['oracle_sha256'][:12]}` (frozen value in classifier/ORACLE-FREEZE.md). "
             f"{len(rows)} runs; verification: {(OUT / 'VERIFY.txt').read_text().strip()}.", "",
             "| Library (arm) | Version | Surfaced | Status only | Silent | Controls accepted |",
             "| --- | --- | ---: | ---: | ---: | ---: |"]
    for lib in libs:
        rs = [r for r in rows if r["library"] == lib]
        c = Counter(r["outcome"] for r in rs)
        ctl = [r for r in rs if r["fault"] is None]
        lines.append(f"| {lib} | {rs[0]['version']} | {c['surfaced']} | {c['status_only']} | {c['silent']} | "
                     f"{sum(r['ceremony_accepted'] for r in ctl)} of {len(ctl)} |")
    lines += ["", "## Faults not surfaced as an error", "", "| Library (arm) | Case | Outcome | What the caller is given |",
              "| --- | --- | --- | --- |"]
    for r in rows:
        if r["outcome"] in ("status_only", "silent"):
            lines.append(f"| {r['library']} | {r['case']} | {r['outcome']} | `{json.dumps(r['record']['fields'])}` |")
    lines += ["", "## Other oracles on the same runs", "",
              "Any error: the call raised or returned an error. Output differential: whether the ceremony was accepted, "
              "read as an integrator who refuses on an error or on the library's top-level verdict (`verified`, `success`) "
              "and on nothing else would read it. "
              "Scored over the 17 fault cases per library.", "",
              "| Library (arm) | Caller-boundary oracle: not surfaced | Any error: missed | Output differential: accepted |",
              "| --- | ---: | ---: | ---: |"]
    for lib in libs:
        rs = [r for r in rows if r["library"] == lib and r["fault"]]
        nos = sum(r["outcome"] != "surfaced" for r in rs)
        miss = sum(not r["observations"]["returned_error"] for r in rs)
        acc = sum(not r["observations"]["returned_error"] and r["record"]["fields"].get("verified", True) is not False
                  and r["record"]["fields"].get("success", True) is not False for r in rs)
        lines.append(f"| {lib} | {nos} | {miss} | {acc} |")
    (OUT / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
