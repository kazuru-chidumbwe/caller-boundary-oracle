#!/usr/bin/env python3
"""Score the mutation baseline: which oracle kills which mutant (mutation/DESIGN.md, parts 3 and 4).

A mutant is killed by an oracle if, on at least one run, that oracle's verdict differs from its
verdict on the same run of the unmutated library (the REF run). Verdicts per run:

  CBO       the outcome of Algorithm 1
  any-error whether the call returned an error
  output    rejected, or accepted with the access control established (PACE or BAC)
  p4        whether the failure was indicated at all (error or status field), with no delivery check

Runs against the independent chip count as different only if the rerun differs too. Mutants
that did not compile, and mutants with a crashed or timed-out run, are reported separately and
scored for no oracle.

Usage: python3 mutation/score.py --runs ~/cbo/mutruns/runs   (writes mutation/out/)
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORACLES = ("cbo", "any_error", "output", "p4")
OPS = ("O1", "O2", "O3", "O4", "O5")
OP_NAME = {"O1": "drop raise", "O2": "error to success", "O3": "swallow in catch", "O4": "skip status write", "O5": "invert check"}


def access(run: dict) -> str:
    if "established" in run:   # WebAuthn runs (T62): acceptance by the library's top-level verdict; absent in eMRTD runs
        return run["established"]
    ac = (run.get("access_control") or "").upper()
    if ac.startswith("PACE"):
        return "PACE"
    if ac.startswith("BAC"):
        return "BAC"
    if run.get("bac_success") is True:
        return "BAC"
    if run.get("bac_success") is False:
        return "PACE"
    return "?"


def verdicts(run: dict) -> dict[str, object]:
    obs = run.get("observation") or {}
    err = bool(obs.get("returned_error"))
    return {
        "cbo": run.get("outcome"),
        "any_error": err,
        "output": "reject" if err else ("accept", access(run)),
        "p4": err or bool(obs.get("status_signal")),
    }


def effective(run: dict, ref: dict) -> dict:
    """Use the rerun's agreement with the reference to discard one-off differences on the independent chip."""
    rerun = run.get("rerun")
    if rerun and rerun.get("status") == "ok" and verdicts(rerun) == verdicts(ref):
        return ref
    return run


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--runs", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=ROOT / "mutation" / "out")
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)

    refs: dict[str, dict[str, dict]] = {}
    for d in a.runs.glob("REF-*"):
        if (d / "done.json").exists():
            refs[d.name[4:]] = {r["scenario_id"]: r for r in json.loads((d / "done.json").read_text(encoding="utf-8"))["runs"]}

    rows, transitions, only_cbo = [], Counter(), []
    for d in sorted(a.runs.glob("M1-*")):
        f = d / "done.json"
        if not f.exists():
            continue
        res = json.loads(f.read_text(encoding="utf-8"))
        m = res["mutant"]
        if f"{m['library']}-{m['version']}" not in refs:
            continue
        row = {k: m[k] for k in ("mutant_id", "site_id", "library", "version", "step", "operator")}
        row |= {"build": res["build"], "crash": False, **{o: False for o in ORACLES}}
        if res["build"] != "ok":
            rows.append(row)
            continue
        ref = refs[f"{m['library']}-{m['version']}"]
        diffs = []
        for run in res["runs"]:
            r0 = ref[run["scenario_id"]]
            if run["status"] != "ok":
                row["crash"] = True
                continue
            run = effective(run, r0)
            v, v0 = verdicts(run), verdicts(r0)
            for o in ORACLES:
                if v[o] != v0[o]:
                    row[o] = True
            if v["cbo"] != v0["cbo"]:
                diffs.append((v0["cbo"], v["cbo"], run["scenario_id"]))
        if row["crash"]:
            for o in ORACLES:
                row[o] = False
        elif row["cbo"] and not (row["any_error"] or row["output"] or row["p4"]):
            only_cbo.append({**row, "changes": diffs})
            for before, after, _ in diffs:
                transitions[(before, after)] += 1
        rows.append(row)

    fields = ["mutant_id", "site_id", "library", "version", "step", "operator", "build", "crash", *ORACLES]
    with (a.out / "kills.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)
    (a.out / "only-cbo.json").write_text(json.dumps(only_cbo, indent=1), encoding="utf-8")

    scored = [r for r in rows if r["build"] == "ok" and not r["crash"]]
    md = ["# Mutation baseline results (generated by mutation/score.py)", "",
          f"Mutants: {len(rows)} generated and run; {sum(r['build'] == 'failed' for r in rows)} did not compile; "
          f"{sum(r['build'] == 'ok' and r['crash'] for r in rows)} had a crashed or timed-out run; {len(scored)} scored.", "",
          "## Mutants killed, by library and operator", "",
          "| library | operator | scored | CBO | any error | output differential | ICAO P4 verdict | only CBO | no oracle |",
          "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    groups = defaultdict(list)
    for r in scored:
        groups[(r["library"], r["operator"])].append(r)
        groups[("all", r["operator"])].append(r)
        groups[("all", "all")].append(r)
    for (lib, op), rs in sorted(groups.items(), key=lambda kv: (kv[0][0] == "all", kv[0])):
        only = sum(r["cbo"] and not (r["any_error"] or r["output"] or r["p4"]) for r in rs)
        none = sum(not any(r[o] for o in ORACLES) for r in rs)
        name = op if op == "all" else f"{op} {OP_NAME[op]}"
        md.append(f"| {lib} | {name} | {len(rs)} | " + " | ".join(str(sum(r[o] for r in rs)) for o in ORACLES)
                  + f" | {only} | {none} |")
    md += ["", "## How the outcome changed where only CBO noticed (per run)", "",
           "| reference outcome | mutant outcome | runs |", "| --- | --- | ---: |"]
    for (b, aft), n in transitions.most_common():
        md.append(f"| {b} | {aft} | {n} |")
    md += ["", "## Killed by a baseline but not by CBO", ""]
    rev = [r for r in scored if not r["cbo"] and (r["any_error"] or r["output"] or r["p4"])]
    md.append(f"{len(rev)} mutants (expected only where the fault was not delivered; listed in kills.csv).")
    (a.out / "RESULTS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
