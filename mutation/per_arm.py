#!/usr/bin/env python3
"""Per-arm scoring of the mutation runs (mutation/DESIGN.md, change 8).

The unit is a (mutant, arm) pair: an arm is one library build plus one caller choice, the unit in
which the paper reports behaviour (Section 3.4). For each pair, runs are split by kind:

  delivered  the injected failure was delivered in the reference and in the mutant run; what the
             caller is told about the failure can change
  delivery   whether the failure was delivered changed
  control    nothing injected (controls, positive control): a change is ordinary breakage

A pair is a failure-reporting change when the caller-boundary outcome differs on at least one
delivered run. For those pairs the script reports which oracles see the change on the delivered
runs, by kind of change, and McNemar's exact test for each baseline against the caller-boundary
oracle. Breakage and delivery changes are reported separately.

Usage: python3 mutation/per_arm.py --runs ~/cbo/mutruns/runs [--out mutation/out]
"""

from __future__ import annotations

import argparse
import json
import math
from collections import Counter, defaultdict
from pathlib import Path

from score import effective, verdicts

ORACLES = ("cbo", "any_error", "output", "p4")
NAMES = {"cbo": "caller-boundary", "any_error": "any error", "output": "output differential", "p4": "ICAO P4 verdict"}
SCORED = {"silent", "status_only", "surfaced"}
RANK = {"silent": 0, "status_only": 1, "surfaced": 2}


def arm_of(run: dict, library: str) -> str:
    sid = run["scenario_id"]
    i = sid.find(f"-{library}-")
    return sid[i + 1:] if i >= 0 else sid


def is_control(sid: str) -> bool:
    return "CTRL-" in sid or "pace-success" in sid


def mcnemar_exact(b: int, c: int) -> float:
    """Two-sided exact McNemar p-value for b and c discordant pairs."""
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    p = sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n
    return min(1.0, 2 * p)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--runs", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent / "out")
    a = ap.parse_args()
    refs = {d.name[4:]: {r["scenario_id"]: r for r in json.loads((d / "done.json").read_text())["runs"]}
            for d in a.runs.glob("REF-*") if (d / "done.json").exists()}

    pairs: dict[tuple, dict] = {}
    for d in sorted(a.runs.glob("M1-*")):
        res = json.loads((d / "done.json").read_text())
        m = res["mutant"]
        if res["build"] != "ok" or any(r["status"] != "ok" for r in res["runs"]):
            continue
        ref = refs.get(f"{m['library']}-{m['version']}")
        if ref is None:
            continue
        for run in res["runs"]:
            r0 = ref[run["scenario_id"]]
            run = effective(run, r0)
            v, v0 = verdicts(run), verdicts(r0)
            key = (m["mutant_id"], arm_of(run, m["library"]))
            p = pairs.setdefault(key, {"library": m["library"], "operator": m["operator"], "site": m["site_id"],
                                       "delivered": set(), "delivery": set(), "control": set(), "changes": []})
            if is_control(run["scenario_id"]):
                kind = "control"
            elif v0["cbo"] in SCORED and v["cbo"] in SCORED:
                kind = "delivered"
            else:
                kind = "delivery"
            seen = {o for o in ORACLES if v[o] != v0[o]}
            p[kind] |= seen
            if kind == "delivered" and "cbo" in seen:
                p["changes"].append((v0["cbo"], v["cbo"], tuple(sorted(seen - {"cbo"}))))

    reporting = {k: p for k, p in pairs.items() if "cbo" in p["delivered"]}
    lines = ["# Per-arm mutation results (generated by mutation/per_arm.py)", "",
             f"(mutant, arm) pairs scored: {len(pairs)}. Pairs with a failure-reporting change on a delivered run: "
             f"{len(reporting)} (from {len({k[0] for k in reporting})} mutants, "
             f"{len({p['site'] for p in reporting.values()})} sites).", "",
             "## Failure-reporting changes: which oracle sees them (delivered runs only)", "",
             "| oracle | pairs detected | of | missed | McNemar vs caller-boundary (exact p) |",
             "| --- | ---: | ---: | ---: | ---: |"]
    n = len(reporting)
    for o in ORACLES:
        det = sum(o in p["delivered"] for p in reporting.values())
        if o == "cbo":
            lines.append(f"| {NAMES[o]} | {det} | {n} | {n - det} | n/a |")
            continue
        b = sum(("cbo" in p["delivered"]) and (o not in p["delivered"]) for p in reporting.values())
        c = sum((o in p["delivered"]) and ("cbo" not in p["delivered"]) for p in reporting.values())
        lines.append(f"| {NAMES[o]} | {det} | {n} | {n - det} | {mcnemar_exact(b, c):.2g} |")

    lines += ["", "## By kind of change (pairs; a pair can show more than one kind)", "",
              "| reference outcome | mutant outcome | direction | pairs | any error sees | output differential sees | ICAO P4 sees |",
              "| --- | --- | --- | ---: | ---: | ---: | ---: |"]
    kinds = defaultdict(lambda: [set(), Counter()])
    for k, p in reporting.items():
        for before, after, others in p["changes"]:
            entry = kinds[(before, after)]
            if k not in entry[0]:
                entry[0].add(k)
                for o in others:
                    entry[1][o] += 1
    for (before, after), (ks, seen) in sorted(kinds.items(), key=lambda kv: -len(kv[1][0])):
        direction = "hides" if RANK[after] < RANK[before] else "reveals"
        lines.append(f"| {before} | {after} | {direction} | {len(ks)} | {seen['any_error']} | {seen['output']} | {seen['p4']} |")

    lines += ["", "## By library and operator (failure-reporting pairs)", "",
              "| library | operator | pairs | caller-boundary | any error | output differential | ICAO P4 |",
              "| --- | --- | ---: | ---: | ---: | ---: | ---: |"]
    group = defaultdict(list)
    for p in reporting.values():
        group[(p["library"], p["operator"])].append(p)
    for (lib, op), ps in sorted(group.items()):
        lines.append(f"| {lib} | {op} | {len(ps)} | " + " | ".join(str(sum(o in p['delivered'] for p in ps)) for o in ORACLES) + " |")

    # Reachability (change 6): a pair is reached when the probe saw its site on any run of the arm.
    reach_file = a.out / "reach.json"
    if reach_file.exists():
        reach = json.loads(reach_file.read_text())
        for (mid, arm), p in pairs.items():
            lib_ver = f"{p['library']}-{mid.split('-')[2]}"
            runs = reach.get(lib_ver, {}).get("reached", {})
            p["reached"] = any(p["site"] in sites for sid, sites in runs.items() if arm_of({"scenario_id": sid}, p["library"]) == arm)
        reached = [p for p in pairs.values() if p["reached"]]
        changed_unreached = [k for k, p in pairs.items() if not p["reached"] and (p["delivered"] or p["delivery"] or p["control"])]
        rep_reached = [p for p in reporting.values() if p["reached"]]
        lines += ["", "## Reachability (probe, change 6)", "",
                  f"- (mutant, arm) pairs whose site ran on that arm: {len(reached)} of {len(pairs)}.",
                  f"- Pairs with any change at a site the probe never saw run: {len(changed_unreached)} (must be 0; a non-zero count means the probe missed a site)."
                  + (f" Examples: {changed_unreached[:5]}" if changed_unreached else ""),
                  f"- Failure-reporting pairs among reached pairs: {len(rep_reached)} of {len(reached)}."]

    # Deduplication: the same site, operator and caller role at different gmrtd releases count once.
    def role(arm: str) -> str:
        """Arm without the gmrtd release: gmrtd-64bd6ab-default -> gmrtd-default."""
        for pin in ("8fea245", "64bd6ab", "b861835"):
            arm = arm.replace(f"-{pin}-", "-")
        return arm
    dedup: dict[tuple, set] = {}
    for (mid, arm), p in reporting.items():
        k = (p["site"], p["operator"], role(arm))
        dedup.setdefault(k, set()).update(p["delivered"])
    lines += ["", "## Failure-reporting changes after deduplication (site, operator, caller role)", "",
              "| oracle | detected | of | missed | McNemar vs caller-boundary (exact p) |",
              "| --- | ---: | ---: | ---: | ---: |"]
    for o in ORACLES:
        det = sum(o in s for s in dedup.values())
        if o == "cbo":
            lines.append(f"| {NAMES[o]} | {det} | {len(dedup)} | {len(dedup) - det} | n/a |")
            continue
        b = sum(("cbo" in s) and (o not in s) for s in dedup.values())
        c = sum((o in s) and ("cbo" not in s) for s in dedup.values())
        lines.append(f"| {NAMES[o]} | {det} | {len(dedup)} | {len(dedup) - det} | {mcnemar_exact(b, c):.2g} (b={b}, c={c}) |")

    breakage = [p for p in pairs.values() if p["control"]]
    delivery = [p for p in pairs.values() if "cbo" in p["delivery"] and "cbo" not in p["delivered"]]
    lines += ["", "## Not failure reporting", "",
              f"- Ordinary breakage (a change on a control run, nothing injected): {len(breakage)} pairs; seen by "
              + ", ".join(f"{NAMES[o]} {sum(o in p['control'] for p in breakage)}" for o in ORACLES) + ".",
              f"- Delivery changed only (the failure is no longer, or now, delivered): {len(delivery)} pairs; seen by "
              + ", ".join(f"{NAMES[o]} {sum(o in p['delivery'] for p in delivery)}" for o in ORACLES) + "."]
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "PER-ARM.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
