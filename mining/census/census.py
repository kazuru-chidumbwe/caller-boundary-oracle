#!/usr/bin/env python3
"""Library census: which open-source eMRTD reader libraries exist, and why five were studied.

Rule (fixed before screening, 8 October 2026):

  step 1  union of GitHub repository searches (queries in QUERIES, run on the date in raw/DATE;
          forks are excluded by the search)
  step 2  on topic: name, description or topics mention a passport, MRTD, ICAO 9303, eMRTD,
          e-passport or travel document
  step 3  implements PACE: the default branch parses PACEInfo or the PACE object identifier
          (0.4.0.127.0.7.2.2.4) and contains a PACE mapping (generic or integrated mapping,
          nonce mapping); checked on a shallow clone (screen.py, lab)
  step 4  is a library: ships package metadata that another program can depend on (go.mod outside
          a main-only tree, pom.xml or build.gradle with a library artifact, a .csproj that is not
          only an executable, pubspec.yaml, Package.swift or a podspec, Cargo.toml with [lib],
          setup.py or pyproject.toml, package.json with a main or exports entry)

Every exclusion keeps its reason. Usage:
  python mining/census/census.py candidates      (local: raw search JSON -> candidates.csv)
  python mining/census/census.py report           (local: candidates.csv + screen.csv -> CENSUS.md)
"""

from __future__ import annotations

import csv
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
QUERIES = ["emrtd", "mrtd", "icao 9303", "epassport nfc", "e-passport reader", "passport nfc reader",
           "nfc passport", "passport chip", "travel document reader", "pace bac passport"]
ON_TOPIC = re.compile(r"passport|mrtd|9303|travel.?document|e-?id\b|eid card", re.I)


def candidates() -> None:
    seen = {}
    for q in QUERIES:
        f = HERE / "raw" / (q.replace(" ", "_") + ".json")
        data = json.loads(f.read_text(encoding="utf-8"))
        for item in data.get("items", []):
            seen.setdefault(item["full_name"], {
                "repo": item["full_name"], "url": item["html_url"], "language": item.get("language") or "",
                "stars": item.get("stargazers_count", 0), "archived": item.get("archived", False),
                "pushed": (item.get("pushed_at") or "")[:10], "description": (item.get("description") or "").replace("\n", " "),
                "topics": " ".join(item.get("topics") or []), "queries": []})
            seen[item["full_name"]]["queries"].append(q)
    rows = []
    for r in seen.values():
        text = " ".join([r["repo"], r["description"], r["topics"]])
        r["on_topic"] = bool(ON_TOPIC.search(text))
        r["queries"] = "; ".join(r["queries"])
        rows.append(r)
    rows.sort(key=lambda r: (-r["stars"], r["repo"]))
    with (HERE / "candidates.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print(f"step 1: {len(rows)} unique repositories; step 2 on topic: {sum(r['on_topic'] for r in rows)}")


def report() -> None:
    cand = list(csv.DictReader((HERE / "candidates.csv").open(encoding="utf-8")))
    screen = {r["repo"]: r for r in csv.DictReader((HERE / "screen.csv").open(encoding="utf-8"))}
    on = [c for c in cand if c["on_topic"] == "True"]
    pace = [c for c in on if screen.get(c["repo"], {}).get("pace") == "yes"]
    lib = [c for c in pace if screen[c["repo"]].get("library") == "yes"]
    lines = ["# eMRTD reader library census (generated by mining/census/census.py)", "",
             f"Searches run {(HERE / 'raw' / 'DATE').read_text().strip()} on GitHub: " + ", ".join(f'"{q}"' for q in QUERIES) + ".", "",
             "| Step | Rule | Remaining |", "| --- | --- | ---: |",
             f"| 1 | Union of the searches, forks excluded | {len(cand)} |",
             f"| 2 | On topic (passport, MRTD, ICAO 9303, travel document) | {len(on)} |",
             f"| 3 | Implements PACE (PACEInfo or PACE OID, and a PACE mapping) | {len(pace)} |",
             f"| 4 | Is a library another program can depend on | {len(lib)} |", "",
             "## Libraries after step 4", "", "| Repository | Language | Stars | Last push | Studied | Reason if not studied |",
             "| --- | --- | ---: | --- | --- | --- |"]
    for c in lib:
        s = screen[c["repo"]]
        lines.append(f"| {c['repo']} | {c['language']} | {c['stars']} | {c['pushed']} | {s.get('studied', '')} | {s.get('note', '')} |")
    lines += ["", "## Excluded at step 3 or 4 (on-topic repositories)", "", "| Repository | Language | Step | Reason |", "| --- | --- | --- | --- |"]
    for c in on:
        s = screen.get(c["repo"], {})
        if s.get("pace") != "yes":
            lines.append(f"| {c['repo']} | {c['language']} | 3 | {s.get('note') or 'no PACE implementation found'} |")
        elif s.get("library") != "yes":
            lines.append(f"| {c['repo']} | {c['language']} | 4 | {s.get('note') or 'application, not a library'} |")
    (HERE / "CENSUS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:14]))


if __name__ == "__main__":
    {"candidates": candidates, "report": report}[sys.argv[1]]()
